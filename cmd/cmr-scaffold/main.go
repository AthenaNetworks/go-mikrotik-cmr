// Command cmr-scaffold decodes the captured controller scaffold blob
// (docs/samples/controller-config.hex) into the structured catalog that
// pkg/cmr.EncodeConfigScope rebuilds from — it generates pkg/cmr/scaffold_catalog.go.
//
// The captured blob is the id9 object stream a real RouterOS controller sends a
// freshly paired device. This tool strips the generated envelope (flag + handle),
// splits each object's key/value into m3 chunks, names the 0x07f0-family type
// references, and emits the rest verbatim, so the result reproduces the capture
// byte-for-byte (verified by pkg/cmr round-trip tests) while being structured Go
// rather than an opaque blob. Re-run it if the captured scaffold is refreshed:
//
//	go run ./cmd/cmr-scaffold docs/samples/controller-config.hex > pkg/cmr/scaffold_catalog.go
package main

import (
	"encoding/hex"
	"fmt"
	"os"
	"path/filepath"
	"strings"

	"github.com/athenanetworks/cmr-server/pkg/m3"
)

type object struct {
	key, value string
	index      byte
}

func main() {
	if len(os.Args) != 2 {
		fmt.Fprintln(os.Stderr, "usage: cmr-scaffold <controller-config.hex> > scaffold_catalog.go")
		os.Exit(2)
	}
	raw, err := os.ReadFile(os.Args[1])
	if err != nil {
		fmt.Fprintln(os.Stderr, "read:", err)
		os.Exit(1)
	}
	blob, err := hex.DecodeString(strings.TrimSpace(string(raw)))
	if err != nil {
		fmt.Fprintln(os.Stderr, "hex:", err)
		os.Exit(1)
	}

	var handles []string
	var objs []object
	for _, f := range m3.StreamAll(blob) {
		if f.ID != 9 {
			fmt.Fprintf(os.Stderr, "warning: unexpected top-level field id %d\n", f.ID)
			continue
		}
		body, err := m3.Decode(f.Value)
		if err != nil {
			fmt.Fprintln(os.Stderr, "decode body:", err)
			os.Exit(1)
		}
		key, _ := body.GetBytes(74)
		value, hasValue := body.GetBytes(75)
		idx, _ := body.GetBytes(64)
		flag, _ := body.GetBytes(29)
		handle, _ := body.GetBytes(21)
		if len(flag) != 1 || flag[0] != 0x10 {
			fmt.Fprintf(os.Stderr, "warning: object flag %x != 0x10 (not a clean capture)\n", flag)
		}
		if len(handle) == 0 || len(idx) != 1 {
			fmt.Fprintln(os.Stderr, "object missing handle or index")
			os.Exit(1)
		}
		handles = append(handles, fmt.Sprintf("0x%02x", handle[0]))
		o := object{key: chunkList(key), index: idx[0]}
		if hasValue {
			o.value = chunkList(value)
		}
		objs = append(objs, o)
	}

	var b strings.Builder
	// Emit a stable repo-relative source path, independent of the invocation dir.
	fmt.Fprintf(&b, "// Code generated by cmd/cmr-scaffold from docs/samples/%s. DO NOT EDIT.\n\n", filepath.Base(os.Args[1]))
	fmt.Fprint(&b, "package cmr\n\n")
	fmt.Fprint(&b, "// scopeHandles is the id21 handle-counter sequence a real controller assigns\n")
	fmt.Fprint(&b, "// to the config-scope rows, captured verbatim (note the discontinuity).\n")
	fmt.Fprintf(&b, "var scopeHandles = []byte{%s}\n\n", strings.Join(handles, ", "))
	fmt.Fprint(&b, "// configScopeCatalog is the decoded config-scope object burst: each row's\n")
	fmt.Fprint(&b, "// key/value as m3 chunks (0x07f0-family type refs as RefChunk, the rest\n")
	fmt.Fprint(&b, "// verbatim as HexChunk) plus its object index. See scaffold.go.\n")
	fmt.Fprint(&b, "var configScopeCatalog = []scopeObject{\n")
	for i, o := range objs {
		fmt.Fprintf(&b, "\t{ // handle %s\n", handles[i])
		fmt.Fprintf(&b, "\t\tkey:   []Chunk{%s},\n", o.key)
		if o.value != "" {
			fmt.Fprintf(&b, "\t\tvalue: []Chunk{%s},\n", o.value)
		}
		fmt.Fprintf(&b, "\t\tindex: 0x%02x,\n", o.index)
		fmt.Fprint(&b, "\t},\n")
	}
	fmt.Fprint(&b, "}\n")

	fmt.Print(b.String())
}

// chunkList splits a field value into m3 chunks and renders them as Go Chunk
// constructors: a 4-byte 0x..07 type reference as RefChunk, anything else as a
// HexChunk of its raw bytes.
func chunkList(v []byte) string {
	var parts []string
	for p := 0; p < len(v); {
		d, n, err := m3.FirstChunk(v[p:])
		if err != nil || n == 0 {
			parts = append(parts, fmt.Sprintf("HexChunk(%q)", hex.EncodeToString(v[p:])))
			break
		}
		p += n
		if len(d) == 4 && d[3] == 0x07 {
			ref := uint32(d[0]) | uint32(d[1])<<8 | uint32(d[2])<<16 | uint32(d[3])<<24
			parts = append(parts, fmt.Sprintf("RefChunk(0x%08x)", ref))
		} else {
			parts = append(parts, fmt.Sprintf("HexChunk(%q)", hex.EncodeToString(d)))
		}
	}
	return strings.Join(parts, ", ")
}
